let seed = 20251006; const rnd = () => { seed |= 0; seed = seed + 0x6D2B79F5 | 0; let t = Math.imul(seed ^ seed >>> 15, 1 | seed); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; };
const shuffle = a => { a = a.slice(); for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
const range = n => [...Array(n).keys()];
function fullGrid(n) {
  const [br, bc] = E.dims(n), pat = (a, b) => (bc * (a % br) + Math.floor(a / br) + b) % n, digits = shuffle(range(n).map(x => x + 1));
  const grp = (cnt, size) => shuffle(range(cnt)).flatMap(x => shuffle(range(size)).map(y => x * size + y)), rows = grp(n / br, br), cols = grp(n / bc, bc);
  return rows.flatMap(a => cols.map(b => digits[pat(a, b)]));
}
function dig(sol, n, spec) {
  const g = sol.slice(); let holes = 0;
  for (const i of shuffle(range(n * n))) {
    if (spec.holes && holes >= spec.holes) break;
    const keep = g[i]; g[i] = 0;
    const ok = spec.tech != null ? E.rate(g, n, spec.tech).solved : E.countSolutions(g, n, 2).count === 1;
    if (!ok) g[i] = keep; else holes++;
  }
  return { g, holes };
}
